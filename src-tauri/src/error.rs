use crate::agents::types::AgentError;
use crate::backends::types::BackendError;
use crate::credentials::types::CredentialError;
use crate::inference::types::InferenceError;
use crate::network::types::NetworkError;
use crate::runtime::types::RuntimeError;
use crate::settings::types::SettingsError;
use crate::sync::types::SyncError;
use crate::workspace::types::WorkspaceError;

/// Top-level error type for all Tauri commands. This is the only error type that crosses the
/// IPC boundary
///
/// Sub-module errors ([`BackendError`], [`SyncError`]) convert automatically via [`From`] impls
/// generated by `thiserror`, so command handlers can use `?` freely across both subsystems.
#[derive(Debug, thiserror::Error)]
pub enum AppError {
    #[error(transparent)]
    Backend(#[from] BackendError),
    #[error(transparent)]
    Sync(#[from] SyncError),
    #[error(transparent)]
    Runtime(#[from] RuntimeError),
    #[error(transparent)]
    Network(#[from] NetworkError),
    #[error(transparent)]
    Agent(#[from] AgentError),
    #[error(transparent)]
    Inference(#[from] InferenceError),
    #[error(transparent)]
    Settings(#[from] SettingsError),
    #[error(transparent)]
    Workspace(#[from] WorkspaceError),
    #[error(transparent)]
    Credential(#[from] CredentialError),
    /// The requested sandbox has no active sync session — it has not been deployed.
    #[error("sandbox {0:?} is not deployed")]
    NotDeployed(String),
    /// The sandbox has unsynced changes on the remote host. The frontend surfaces this as a
    /// confirmation dialog and retries the destroy with `force = true`.
    #[error("sandbox {name:?} has unsynced changes on {host}; confirm to destroy and discard them")]
    UnsyncedChanges { name: String, host: String },
    /// Podman machine is stopped or its rootless socket is not ready.
    #[error("Podman is not ready: {0}")]
    PodmanUnavailable(String),
    /// `provision_podman` installed WSL2 and the platform component needs a reboot before
    /// `podman machine init` can proceed.
    #[error("Windows must be restarted to finish installing WSL2: {0}")]
    PodmanRebootRequired(String),
}

impl AppError {
    /// A stable string discriminant for each variant, used by the frontend to branch on error
    /// kind without parsing the human-readable message.
    fn kind(&self) -> &'static str {
        match self {
            AppError::Backend(_) => "Backend",
            AppError::Sync(_) => "Sync",
            AppError::Runtime(_) => "Runtime",
            AppError::Network(_) => "Network",
            AppError::Agent(_) => "Agent",
            AppError::Inference(_) => "Inference",
            AppError::Settings(_) => "Settings",
            AppError::Workspace(_) => "Workspace",
            AppError::Credential(_) => "Credential",
            AppError::NotDeployed(_) => "NotDeployed",
            AppError::UnsyncedChanges { .. } => "UnsyncedChanges",
            AppError::PodmanUnavailable(_) => "PodmanUnavailable",
            AppError::PodmanRebootRequired(_) => "PodmanRebootRequired",
        }
    }
}

/// Serialise as `{ kind, message }` so the frontend can branch on `kind` with full type safety
/// rather than matching substrings of `message`.
impl serde::Serialize for AppError {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::ser::Serializer,
    {
        use serde::ser::SerializeStruct;
        let mut s = serializer.serialize_struct("AppError", 2)?;
        s.serialize_field("kind", self.kind())?;
        s.serialize_field("message", &self.to_string())?;
        s.end()
    }
}
